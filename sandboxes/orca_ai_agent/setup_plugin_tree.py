def decode(name):
    digest, chunks = PAYLOAD[name]
    raw = zlib.decompress(base64.b85decode("".join(chunks).encode("ascii")))
    if hashlib.sha256(raw).hexdigest() != digest:
        raise SystemExit(f"Corrupted payload for {name} (checksum mismatch); re-download this script.")
    return raw


def check_version(target):
    """The PEP 723 header version and PLUGIN_VERSION must agree and must not be a legacy 1.0."""
    source = (target / "plugin.py").read_text(encoding="utf-8")
    header = re.search(r'(?m)^# version = "([^"]+)"', source)
    constant = re.search(r'(?m)^PLUGIN_VERSION = "([^"]+)"', source)
    if not header or not constant:
        raise SystemExit("Could not read the plugin version from plugin.py.")
    if header.group(1) != constant.group(1):
        raise SystemExit(f"Version mismatch: header {header.group(1)} != PLUGIN_VERSION {constant.group(1)}")
    if re.fullmatch(r"v?1\.0(\.0)?", constant.group(1)):
        raise SystemExit(f"Refusing legacy version {constant.group(1)}.")
    return constant.group(1)


def main():
    parser = argparse.ArgumentParser(description="Create the Orca AI Agent plugin folder.")
    parser.add_argument("--target", type=Path, default=DEFAULT_TARGET, help=f"output folder (default: {DEFAULT_TARGET})")
    parser.add_argument("--force", action="store_true", help="overwrite existing files that differ (a .bak copy is kept)")
    parser.add_argument("--run-tests", action="store_true", help="run embed_panel.py --check and the unit tests afterwards")
    args = parser.parse_args()

    target = args.target.resolve()
    payloads = {name: decode(name) for name in PAYLOAD}

    conflicts = [n for n, raw in payloads.items() if (target / n).exists() and (target / n).read_bytes() != raw]
    if conflicts and not args.force:
        print("These files already exist and differ (use --force to overwrite):")
        for name in conflicts:
            print("  -", target / name)
        return 1

    for name, raw in payloads.items():
        path = target / name
        path.parent.mkdir(parents=True, exist_ok=True)
        if path.exists():
            if path.read_bytes() == raw:
                print(f"unchanged  {path}")
                continue
            path.with_name(path.name + ".bak").write_bytes(path.read_bytes())
        path.write_bytes(raw)
        if hashlib.sha256(path.read_bytes()).hexdigest() != hashlib.sha256(raw).hexdigest():
            raise SystemExit(f"Write verification failed for {path}")
        print(f"wrote      {path}")

    print(f"Plugin version: v{check_version(target)} (header and PLUGIN_VERSION match)")

    if args.run_tests:
        for command in ([sys.executable, "embed_panel.py", "--check"], [sys.executable, "-m", "unittest", "test_plugin", "-v"]):
            if subprocess.call(command, cwd=target) != 0:
                return 1
    print(f"\nDone: {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
